/* =========================================================
   Pop-up logic
   ========================================================= */
(function () {
  const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
  const slug = (s) => s.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
  const byKey = {};
  Object.keys(caseStudies).forEach((t) => (byKey[slug(t)] = t));

  const dlg = document.createElement("dialog");
  dlg.className = "cm";
  dlg.setAttribute("aria-label", "Case study");
  document.body.appendChild(dlg);
  let lastFocus = null;

  function media(m, extra) {
    if (!m) return "";
    const cls = "cm-media" + (m.wide ? " wide" : "") + (m.logo ? " logo" : "") + (extra ? " " + extra : "");
    let inner = "";
    if (m.type === "video") inner = `<video controls playsinline preload="metadata"${m.poster ? ` poster="${esc(m.poster)}"` : ""}><source src="${esc(m.src)}"></video>`;
    else if (m.type === "youtube") inner = `<iframe src="https://www.youtube.com/embed/${esc(m.src)}" title="${esc(m.alt || "Video")}" allowfullscreen loading="lazy"></iframe>`;
    else inner = `<img src="${esc(m.src)}" alt="${esc(m.alt || "")}" loading="lazy">`;
    return `<figure class="${cls}">${inner}</figure>`;
  }

  function render(title, c) {
    const paras = (t) => String(t).split("\n\n").map((p) => `<p>${esc(p)}</p>`).join("");
    dlg.innerHTML = `
      <div class="cm-inner">
        <button class="cm-close" type="button" aria-label="Close case study">Close</button>
        <header class="cm-head">
          <span class="cat">${esc(c.category || "")}</span>
          <h2>${esc(title)}</h2>
          ${c.intro ? `<p class="lead">${esc(c.intro)}</p>` : ""}
        </header>
        <dl class="cm-meta">
          ${(c.meta || [["My role", c.role], ["Tools", c.tools], ["Timeline", c.timeline], ["Type", c.type]])
            .filter((x) => x[1]).map((x) => `<div><dt>${x[0]}</dt><dd>${esc(x[1])}</dd></div>`).join("")}
        </dl>
        ${c.hero ? media(c.hero, "hero") : ""}
        ${(c.sections || []).map((s) => `<section class="cm-block"><h3>${esc(s[0])}</h3><div>${paras(s[1])}</div></section>`).join("")}
        ${c.media && c.media.length ? `<div class="cm-gallery">${c.media.map((m) => media(m)).join("")}</div>` : ""}
      </div>`;
    dlg.querySelector(".cm-close").addEventListener("click", () => close());
  }

  function open(title, fromHash) {
    const c = caseStudies[title];
    if (!c) return;
    render(title, c);
    if (!dlg.open) dlg.showModal();
    dlg.scrollTop = 0;
    document.body.classList.add("cm-open");
    if (!fromHash) history.pushState(null, "", "#" + slug(title));
  }

  function close(fromHash) {
    if (dlg.open) dlg.close();
    dlg.querySelectorAll("video").forEach((v) => v.pause());
    dlg.querySelectorAll("iframe").forEach((f) => (f.src = f.src)); // stops YouTube
    document.body.classList.remove("cm-open");
    if (!fromHash && location.hash && byKey[location.hash.slice(1)]) history.back();
    if (lastFocus) { lastFocus.focus({ preventScroll: true }); lastFocus = null; }
  }

  // Click outside the white panel closes it
  dlg.addEventListener("click", (e) => { if (e.target === dlg) close(); });
  // Esc key: let the browser close the dialog, then tidy up
  dlg.addEventListener("cancel", (e) => { e.preventDefault(); close(); });
  // Browser back / forward buttons
  window.addEventListener("popstate", () => {
    const t = byKey[location.hash.slice(1)];
    if (t) open(t, true); else close(true);
  });

  // Connect each project card to its case study (matched by title)
  document.querySelectorAll(".card").forEach((card) => {
    const h = card.querySelector("h3");
    const title = h && h.textContent.trim();
    if (!title || !caseStudies[title]) return;
    if (!card.querySelector(".view")) {
      const t = card.querySelector(".thumb");
      if (t) t.insertAdjacentHTML("beforeend", '<span class="view">View case study</span>');
    }
    card.setAttribute("role", "button");
    card.setAttribute("tabindex", "0");
    card.setAttribute("aria-haspopup", "dialog");
    card.style.cursor = "pointer";
    const go = (e) => { e.preventDefault(); lastFocus = card; open(title); };
    card.addEventListener("click", go);
    card.addEventListener("keydown", (e) => { if (e.key === "Enter" || e.key === " ") go(e); });
  });

  // Opening the site with #kvarteret-thai in the address opens that case study
  const first = byKey[location.hash.slice(1)];
  if (first) open(first, true);
})();
